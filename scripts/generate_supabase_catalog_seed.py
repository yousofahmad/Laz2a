#!/usr/bin/env python3
"""Generate the trusted Supabase catalog seed from src/data/catalog.json."""
from decimal import Decimal, InvalidOperation
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "src/data/catalog.json"
OUTPUT = ROOT / "supabase_catalog_seed.sql"


def sql_text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


products = json.loads(CATALOG.read_text(encoding="utf-8"))
seen = set()
rows = []
for product in products:
    product_id = int(product["id"])
    if product_id in seen or product_id < 1:
        raise SystemExit(f"Invalid or duplicate catalog product ID: {product_id}")
    seen.add(product_id)
    is_collection = bool(product.get("isCollection"))
    raw_price = product.get("price", 75) if is_collection else 10
    try:
        price = Decimal(str(raw_price if raw_price is not None else 75)).quantize(Decimal("0.01"))
    except InvalidOperation as exc:
        raise SystemExit(f"Invalid price for product {product_id}") from exc
    if price < 0:
        raise SystemExit(f"Negative price for product {product_id}")
    title = str(product.get("title", "")).strip()
    if not title:
        raise SystemExit(f"Missing title for product {product_id}")
    rows.append(
        f"  ({product_id}, {sql_text(title)}, {'true' if is_collection else 'false'}, {price:.2f}, true)"
    )

sql = """-- Generated by scripts/generate_supabase_catalog_seed.py; do not edit by hand.
-- Run after supabase_schema.sql and regenerate whenever product titles or prices change.
begin;
update public.catalog_products set active = false;
insert into public.catalog_products (product_id, title, is_collection, unit_price, active)
values
""" + ",\n".join(rows) + "\non conflict (product_id) do update set\n  title = excluded.title,\n  is_collection = excluded.is_collection,\n  unit_price = excluded.unit_price,\n  active = true,\n  updated_at = now();\ncommit;\n"
OUTPUT.write_text(sql, encoding="utf-8")
print(f"Wrote {len(rows)} catalog price records to {OUTPUT}")
